String videoMatchingTr(String source) {
  final exact = source.tr;
  if (exact != source || Get.locale?.languageCode != 'en') return exact;

  final cameraCountdown = RegExp(
    r'^Có thể mở camera sau (\d{2}):(\d{2})$',
  ).firstMatch(source);
  if (cameraCountdown != null) {
    return 'Camera unlocks in ${cameraCountdown[1]}:${cameraCountdown[2]}';
  }
  return source;
}
